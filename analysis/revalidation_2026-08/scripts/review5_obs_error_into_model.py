# 2.  exact box optima by concave-maximisation bisection
# =============================================================================
def _g_quad(delta, mc, oc, t):
    """g(delta) = mc.delta - t*||oc + delta_c||^2  and its gradient (concave)."""
    z = oc + (delta - delta.mean())
    val = float(mc @ delta) - t * float(z @ z)
    grad = mc - 2.0 * t * z
    return -val, -grad


def _g_norm(delta, mc, oc, t):
    """g(delta) = mc.delta - t*||oc + delta_c||  and its gradient (concave)."""
    z = oc + (delta - delta.mean())
    nz = float(np.sqrt(z @ z))
    val = float(mc @ delta) - t * nz
    grad = mc - (t / max(nz, 1e-300)) * z
    return -val, -grad


def _max_g(fun, mc, oc, t, B, n, seed_parts, nrand=0):
    """For t >= 0 the objective is CONCAVE (a linear form minus a convex term), so
    L-BFGS-B from a single feasible start already reaches the global optimum; the
    extra starts are kept only as a numerical cross-check and default to few."""
    starts = [np.zeros(n), np.clip(-oc, -B, B), np.clip(B * np.sign(mc), -B, B)]
    if nrand:
        g = rng_for(*seed_parts)
        starts += [g.uniform(-B, B, n) for _ in range(nrand)]
    best, bx = -np.inf, None
    for x0 in starts:
        res = minimize(fun, np.clip(x0, -B, B), args=(mc, oc, t), jac=True,
                       method="L-BFGS-B", bounds=[(-B, B)] * n,
                       options={"maxiter": 20000, "ftol": 1e-18, "gtol": 1e-16})
        if -res.fun > best:
            best, bx = float(-res.fun), res.x
    return best, bx


def sup_over_box(kind, o, m, B, seed_parts, t_hi=1e4):
    """EXACT supremum over the box |delta_i| <= B of
         kind='beta' : beta = Com/Coo
         kind='r'    : r    = Com/sqrt(Coo*Cmm)
    by bisection on the level t: sup >= t  <=>  max_box (L - t*Q) >= 0, where
    L = Com0 + mc.delta is linear and Q is ||zc||^2 (beta) or sqrt(Cmm)*||zc||
    (r) -- both convex, so the inner maximisation is concave and exact.
    Also returns the argmax delta at the attained level."""
    n = len(o)
    oc = o - o.mean()
    mc = m - m.mean()
    Com0 = float(oc @ mc)
    Cmm = float(mc @ mc)
    if kind == "beta":
        fun = _g_quad
        scale = 1.0
    else:
        fun = _g_norm
        scale = float(np.sqrt(Cmm))

    def feasible(t, nrand=0):
        # max over box of  (Com0 + mc.delta) - t*scale*f(delta)   >= 0 ?
        best, bx = _max_g(fun, mc, oc, t * scale, B, n,
                          seed_parts + (kind, f"t{t:.10g}"), nrand=nrand)
        return Com0 + best, bx

    # the box contains delta = 0, so the supremum is at least the unperturbed
    # value, which is positive for every scheme and record set here; t >= 0
    # therefore keeps the inner problem concave and globally solvable.
    v0, _ = feasible(0.0)
    assert v0 >= 0.0, ("t=0 infeasible: the unperturbed value is negative, so the "
                       "concave bracket below does not apply", kind, seed_parts)
    lo, hi = 0.0, t_hi
    v, _ = feasible(hi)
    if v >= 0:
        return float("inf"), None
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        v, _ = feasible(mid)
        if v >= 0:
            lo = mid
        else:
            hi = mid
    _, xb = feasible(lo, nrand=24)      # cross-check the argmax with more starts
    return float(lo), xb


def min_obs_var_over_box(o, B, seed_parts):
    """min over |delta_i| <= B of var(o + delta) (convex) -> max s_m/s_o."""
    n = len(o)
    oc = o - o.mean()
    zero = np.zeros(n)

    def f(delta, *a):
        z = oc + (delta - delta.mean())
        return float(z @ z), 2.0 * z

    g = rng_for(*seed_parts)
    starts = [zero, np.clip(-oc, -B, B)] + [g.uniform(-B, B, n) for _ in range(8)]
    best, bx = np.inf, None
    for x0 in starts:
        res = minimize(f, np.clip(x0, -B, B), jac=True, method="L-BFGS-B",
                       bounds=[(-B, B)] * n,
                       options={"maxiter": 20000, "ftol": 1e-18, "gtol": 1e-16})
        if res.fun < best:
            best, bx = float(res.fun), res.x
    return best, bx


def b_star_beta(o, m, seed_parts, bmax=20.0):
    """Smallest box amplitude B at which the supremum of beta reaches 1.
    max_box(L - 1*Q) is nondecreasing in B, so bisection is exact."""
    n = len(o)
    oc = o - o.mean()
    mc = m - m.mean()
    Com0 = float(oc @ mc)

    def h(B):
        if B <= 0:
            z = oc
            return Com0 - float(z @ z)
        best, _ = _max_g(_g_quad, mc, oc, 1.0, B, n, seed_parts + (f"B{B:.6g}",))
        return Com0 + best

    if h(0.0) >= 0:
        return 0.0
    if h(bmax) < 0:
        return None
    lo, hi = 0.0, bmax
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        if h(mid) >= 0:
            hi = mid
        else:
            lo = mid
    return float(hi)


def vertex_sup_r_obs(a, y, B):
    """Reproduce obs_uncertainty_v11.unrestricted_box_worstcase: sup of the
    OBSERVED albedo--offset r over the box, by exhaustive 2^n vertex
    enumeration, and return the argmax sign vector."""
    n = len(a)
    ac = a - a.mean()
    yc = y - y.mean()
    C0 = float(ac @ yc); Saa = float(ac @ ac); Syy = float(yc @ yc)
    N = 1 << n
    bits = np.arange(n, dtype=np.int64)
    best, bk = -np.inf, -1
    step = 1 << 16
    for lo in range(0, N, step):
        idx = np.arange(lo, min(lo + step, N), dtype=np.int64)
        S = (((idx[:, None] >> bits) & 1) * 2.0 - 1.0)
        u = S @ ac; v = S @ yc; w = S.sum(1)
        num = C0 + B * u
        den = np.sqrt(Saa * (Syy + 2 * B * v + B * B * (n - w * w / n)))
        rr = num / den
        k = int(np.argmax(rr))
        if rr[k] > best:
            best, bk = float(rr[k]), int(idx[k])
    sv = np.array([1.0 if (bk >> i) & 1 else -1.0 for i in range(n)])
    return best, sv


