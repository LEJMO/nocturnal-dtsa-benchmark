def boot_counts(P, ss, draws):
    """Reproduce the published city-cluster bootstrap EXACTLY (same RNG call
    sequence as review5_core15.model_side) and return it as a multiplicity
    matrix W of shape (draws, n)."""
    cl = np.array([P[s].get("cluster", s) for s in ss])
    uc = sorted(set(cl.tolist()))
    idx_by_c = [np.where(cl == u)[0] for u in uc]
    n = len(ss)
    W = np.zeros((draws, n), float)
    rng = np.random.default_rng(SEED_BOOT)
    for j in range(draws):
        pick = rng.choice(len(uc), size=len(uc), replace=True)
        ii = np.concatenate([idx_by_c[p] for p in pick])
        W[j] = np.bincount(ii, minlength=n)
    return W, uc


def w_metrics(W, C, O, m):
    """Multiplicity-weighted r, s_m/s_o, beta. O may be (D,n) or (n,);
    m is (n,) and is NEVER perturbed."""
    if O.ndim == 1:
        O = O[None, :]
    mo = (W * O).sum(1) / C
    mm = (W * m[None, :]).sum(1) / C
    Oc = O - mo[:, None]
    Mc = m[None, :] - mm[:, None]
    Coo = (W * Oc * Oc).sum(1)
    Cmm = (W * Mc * Mc).sum(1)
    Com = (W * Oc * Mc).sum(1)
    with np.errstate(divide="ignore", invalid="ignore"):
        r = Com / np.sqrt(Coo * Cmm)
        sdr = np.sqrt(Cmm / Coo)
        beta = Com / Coo
    return r, sdr, beta


def ci(v, lo=2.5, hi=97.5):
    v = np.asarray(v, float); v = v[np.isfinite(v)]
    return [float(np.percentile(v, lo)), float(np.percentile(v, hi))]


def tail_block(r, sdr, beta):
    ok = np.isfinite(beta) & np.isfinite(r) & np.isfinite(sdr)
    return dict(
        n_draws=int(ok.sum()),
        P_beta_ge_1=float(np.mean(beta[ok] >= 1.0)),
        P_r_le_0=float(np.mean(r[ok] <= 0.0)),
        P_sdratio_ge_1=float(np.mean(sdr[ok] >= 1.0)),
        beta_median=float(np.median(beta[ok])), beta_ci95=ci(beta[ok]),
        r_median=float(np.median(r[ok])), r_ci95=ci(r[ok]),
        sd_ratio_median=float(np.median(sdr[ok])), sd_ratio_ci95=ci(sdr[ok]))


def spread_block(rs, sdrs, betas, s_obs):
    """Distribution over the error field alone (no resampling)."""
    def q(v):
        return dict(median=float(np.median(v)),
                    mean=float(np.mean(v)),
                    ci95=ci(v), min=float(v.min()), max=float(v.max()))
    return dict(n_draws=int(len(betas)),
                r=q(rs), sd_ratio=q(sdrs), beta=q(betas), s_obs=q(s_obs),
                frac_beta_ge_1=float(np.mean(betas >= 1.0)),
                frac_r_le_0=float(np.mean(rs <= 0.0)),
                frac_sdratio_ge_1=float(np.mean(sdrs >= 1.0)))


def error_only(O, m):
    """Per-draw point metrics with no resampling (weights all 1)."""
    n = O.shape[1]
    mo = O.mean(1)
    Oc = O - mo[:, None]
    mm = m.mean()
    Mc = m - mm
    Coo = (Oc * Oc).sum(1)
    Cmm = float((Mc * Mc).sum())
    Com = Oc @ Mc
    r = Com / np.sqrt(Coo * Cmm)
    sdr = np.sqrt(Cmm / Coo)
    beta = Com / Coo
    s_obs = np.sqrt(Coo / (n - 1))
    return r, sdr, beta, s_obs


